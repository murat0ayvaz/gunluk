/// kind: 'motivation' | 'ayet' | 'hadis' — lang: 'tr' | 'en'
List<QuoteItem> builtInQuotes(String kind, String lang) {
  final list = kind == 'ayet'
      ? _ayet
      : (kind == 'hadis' ? _hadis : _motivation);
  final en = lang == 'en';
  return [
    for (final q in list)
      QuoteItem(en ? q.en : q.tr, en ? q.refEn : q.refTr),
  ];
}
